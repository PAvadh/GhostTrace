"""
Part 5 - official AMLSim sample integration + provenance guards.

The official IBM/AMLSim example ('100vertices-10Kedges', per
https://github.com/IBM/AMLSim/wiki/Download-Example-Data-Set) has NOT been bundled yet
(it was unreachable when Part 5 was built). Tests that need it raise unittest.SkipTest, which
both pytest and run_tests.py report as SKIPPED - never as passed.

Only structural invariants are asserted. Row/account counts quoted by the wiki are checked
softly by the HANDOFF procedure, not hard-coded here, because they have not been verified
against the real files.
"""
import csv
import os
import unittest

from ghost_trace.amlsim_adapter import (
    AMLSIM_REQUIRED_COLUMNS,
    load_amlsim_transactions,
)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_DIR = os.path.join(ROOT, "data", "amlsim")
OFFICIAL_TX = os.path.join(DATA_DIR, "official", "100vertices-10Kedges", "transactions.csv")


def _need_official():
    if not os.path.isfile(OFFICIAL_TX):
        raise unittest.SkipTest(
            "Official AMLSim sample not present at "
            "data/amlsim/official/100vertices-10Kedges/transactions.csv "
            "(see data/amlsim/README.md)."
        )


# ── integration against the real sample (skipped until it is added) ─────────

def test_official_sample_loads_with_native_schema():
    _need_official()
    r = load_amlsim_transactions(OFFICIAL_TX, max_rows=20_000)
    assert r.success, r.error
    assert r.detected_format == "amlsim_native"
    assert r.rows_loaded > 0 and r.rows_loaded + r.rows_skipped == r.rows_attempted
    assert not r.truncated, "sample should fit within max_rows=20000"


def test_official_sample_preserves_original_transaction_and_account_ids():
    _need_official()
    r = load_amlsim_transactions(OFFICIAL_TX, max_rows=20_000)
    assert r.success, r.error
    with open(OFFICIAL_TX, newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    file_ids = {row["tran_id"].strip() for row in rows}
    loaded_ids = {t.tx_id for t in r.ledger.transactions}
    assert loaded_ids <= file_ids and len(loaded_ids) == len(r.ledger.transactions)
    file_accts = {row["orig_acct"].strip() for row in rows} | {row["bene_acct"].strip() for row in rows}
    assert set(r.ledger.accounts) <= file_accts


def test_official_sample_labels_never_enter_the_ledger():
    _need_official()
    r = load_amlsim_transactions(OFFICIAL_TX, max_rows=20_000)
    assert r.success, r.error
    assert all(t.is_ground_truth_fraud is False for t in r.ledger.transactions)
    assert r.ledger.ground_truth_rings == []
    assert set(r.labels) <= {t.tx_id for t in r.ledger.transactions}


# ── always-on guards (no sample needed) ─────────────────────────────────────

def test_required_columns_match_the_wiki_documented_transaction_schema():
    # IBM/AMLSim wiki "Data Schema ... Transactions (transactions.csv)":
    # tran_id, orig_acct, bene_acct, tx_type, base_amt, tran_timestamp, is_sar, alert_id
    wiki_columns = {"tran_id", "orig_acct", "bene_acct", "tx_type", "base_amt",
                    "tran_timestamp", "is_sar", "alert_id"}
    assert set(AMLSIM_REQUIRED_COLUMNS) <= wiki_columns


def test_bundled_csvs_are_declared_as_fixtures_not_official_amlsim():
    readme = os.path.join(DATA_DIR, "README.md")
    assert os.path.isfile(readme)
    text = open(readme, encoding="utf-8").read().lower()
    assert "hand-written" in text and "not generated by ibm amlsim" in text
    assert "test fixture" in text
    # the real sample must not be silently claimed to be present
    assert "not yet included" in text or os.path.isfile(OFFICIAL_TX)
